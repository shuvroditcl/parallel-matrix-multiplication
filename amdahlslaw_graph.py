import matplotlib.pyplot as plt
from google.colab import files

# Updated data from slurm-42070.out
processors = [1, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40]
actual_speedup = [1.00, 3.92, 7.14, 10.46, 13.89, 17.30, 20.73, 24.32, 20.70, 21.91, 24.33]
ideal_speedup = [1, 4, 8, 12, 16, 20, 24, 28, 32, 36, 40]

# Create the plot
plt.figure(figsize=(10, 6))

# Plot actual speedup
plt.plot(processors, actual_speedup, marker='o', linestyle='-', color='#0044cc',
         linewidth=2, markersize=8, label='Actual Speedup')

# Plot ideal linear speedup
plt.plot(processors, ideal_speedup, linestyle='--', color='#e74c3c',
         linewidth=2, label='Ideal Linear Speedup')

# Formatting
plt.title("Parallel Speedup vs. Number of Processors (Amdahl's Law)",
          fontsize=14, fontweight='bold')
plt.xlabel("Number of Processors (p)", fontsize=12)
plt.ylabel("Speedup (S)", fontsize=12)

# Set x-axis ticks to match processor counts exactly
plt.xticks(processors)

# Add grid and legend
plt.grid(True, linestyle='--', alpha=0.7)
plt.legend(loc='upper left', fontsize=11)

# Adjust layout and save the image inside the Colab environment
filename = 'updated_amdahls_law_graph.png'
plt.tight_layout()
plt.savefig(filename, dpi=300)

# Display the plot in the notebook
plt.show()

# Trigger the download to your local computer
files.download(filename)